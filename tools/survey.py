"""Survey how each report is organised, to plan the parsers.

For each year: which text we'd parse (Gutenberg if present, else IA OCR),
its sections, and per section the signals of each layout:
  - diary:   lines opening with a date ("October 21st.--")
  - species: species headings ("Redwing, _Turdus iliacus_.--")
  - station: lines opening with a station name ("_North Maidens._--")
plus station mentions (L.H./L.V.) and day-of-month tokens as a rough size.
Also counts page markers in the Gutenberg HTML (to link records to scans).

Run: python3 -I tools/survey.py > notes/SURVEY.md
"""
import json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
man = json.load(open(os.path.join(ROOT, 'sources', 'MANIFEST.json')))
MONTHS = 'January|February|March|April|May|June|July|August|September|October|November|December|Jan|Feb|Mar|Apr|Aug|Sept|Sep|Oct|Nov|Dec'
SEC = re.compile(r'^\s*_?((?:EAST|WEST|SOUTH|NORTH)[A-Z ,.&]*COAST[A-Z ,.&]*|IRISH COAST[A-Z ,.]*|IRELAND[A-Z ,.]*|HELIGOLAND[A-Z ,.]*|GENERAL REMARKS|SPRING MIGRATION[^a-z]*|AUTUMN MIGRATION[^a-z]*)\.?_?\s*$', re.M)
DIARY = re.compile(rf'^\s*_?(?:{MONTHS})\.? \d{{1,2}}(?:st|nd|rd|th|d)?\.?_?\s*[.:,]?\s*-{{2}}', re.M)
SPECIES = re.compile(r'^\s*[A-Z][a-z]+(?:[- ][A-Za-z]+){0,3},\s+_[A-Z][a-z]+ [a-z]+', re.M)
STATION = re.compile(r'^\s*_[A-Z][A-Za-z\'. ,()]{2,40}\._\s*-{2}', re.M)
STAT_MENTION = re.compile(r'L\.\s?[HV]\.')
DAY = re.compile(r'\b\d{1,2}(?:st|nd|rd|th|d)\b')

print('# Survey of the nine reports\n')
print('Generated by `tools/survey.py`. Counts are signals for planning, not data.\n')
for year in sorted(man, key=int):
    e = man[year]
    if 'gutenberg_txt' in e:
        path, kind = e['gutenberg_txt']['path'], 'Gutenberg'
    else:
        path, kind = e['ia_ocr']['path'], 'IA OCR'
    t = open(os.path.join(ROOT, path), encoding='utf-8', errors='replace').read()
    if '*** START' in t:
        t = t[t.index('*** START'):t.index('*** END') if '*** END' in t else len(t)]
    print(f'## {year} ({kind}: `{path}`, {len(t.split()):,} words)\n')
    if 'gutenberg_html' in e:
        h = open(os.path.join(ROOT, e['gutenberg_html']['path']), encoding='utf-8', errors='replace').read()
        pn = len(re.findall(r'class="pagenum', h))
        print(f'- Gutenberg HTML page markers: {pn}')
    heads = [(m.start(), ' '.join(m.group(1).split())) for m in SEC.finditer(t)]
    heads = [h for i, h in enumerate(heads) if i == 0 or h[1] != heads[i-1][1]]
    bounds = heads + [(len(t), 'END')]
    print('\n| section | words | diary dates | species heads | station heads | L.H./L.V. | day tokens |')
    print('|---|---|---|---|---|---|---|')
    if heads and heads[0][0] > 2000:
        bounds = [(0, '(front matter)')] + bounds
    for (a, name), (b, _) in zip(bounds, bounds[1:]):
        s = t[a:b]
        print(f'| {name[:45]} | {len(s.split()):,} | {len(DIARY.findall(s))} | {len(SPECIES.findall(s))} | '
              f'{len(STATION.findall(s))} | {len(STAT_MENTION.findall(s))} | {len(DAY.findall(s))} |')
    print()
